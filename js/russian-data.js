function getRussianTask(taskId) {
    return RUSSIAN_TASKS.find(task => task.id === taskId);
}

// Функция проверки ответа на карточку
function checkRussianAnswer(cardId, userAnswer, taskId) {
    const task = getRussianTask(taskId);
    if (!task) return false;

    const card = task.cards.find(c => c.id === cardId);
    if (!card) return false;

    const normalizedUser = userAnswer.toLowerCase().trim();
    const normalizedCorrect = card.rule.toLowerCase().trim();

    if (normalizedUser === normalizedCorrect) return true;

    if (card.aliases) {
        return card.aliases.some(alias =>
            normalizedUser === alias.toLowerCase().trim()
        );
    }

    return false;
}

// Функция получения случайных вариантов ответа
function getRandomRussianChoices(correctCardId, count, taskId) {
    const task = getRussianTask(taskId);
    if (!task || task.cards.length < count) return task ? task.cards : [];

    const correctCard = task.cards.find(c => c.id === correctCardId);
    if (!correctCard) return [];

    const wrongCards = task.cards.filter(c => c.id !== correctCardId);
    const shuffled = wrongCards.sort(() => Math.random() - 0.5);
    const choices = shuffled.slice(0, count - 1);

    choices.push(correctCard);
    return choices.sort(() => Math.random() - 0.5);
}

